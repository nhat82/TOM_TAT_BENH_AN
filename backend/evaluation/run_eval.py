def _score_all(context: str, question: str, answer: str) -> dict:
    """
    One Gemini call → structured result with explicit status.

    Return shape
    ────────────
    ok               {"status":"ok",                "faithfulness":f, "answer_relevancy":f, "citation_accuracy":f, "wait_time":0,
                      "judge_input_tokens":n, "judge_output_tokens":n}
    rate_limit_timeout {"status":"rate_limit_timeout","faithfulness":None,..., "wait_time": <total_s>,
                        "judge_input_tokens":0, "judge_output_tokens":0}
    infra_failure    {"status":"infra_failure",     "faithfulness":None,..., "wait_time": <total_s>,
                      "judge_input_tokens":0, "judge_output_tokens":0}
    model_failure    {"status":"model_failure",     "faithfulness":0.0,..., "wait_time": <total_s>,
                      "judge_input_tokens":n, "judge_output_tokens":n}

    Rate-limit policy (free tier: 15 RPM / 1 000 RPD / 250 K TPM)
    ───────────────────────────────────────────────────────────────
    429 → wait exactly as long as the API says, retry.
    Once cumulative wait exceeds _MAX_RATE_LIMIT_WAIT → rate_limit_timeout (score = None).
    Other API errors → exponential back-off up to _ERROR_RETRIES → infra_failure (score = None).
    Malformed model output → model_failure (score = 0.0, counts in averages).
    """
    import re

    prompt = (
        "You are evaluating a Vietnamese medical RAG system.\n"
        "Answer each question below with YES or NO in English only.\n\n"
        f"Context (retrieved patient record sections):\n{context}\n\n"
        f"Question asked by user: {question}\n"
        f"Answer generated by system: {answer}\n\n"
        "Q1 (faithfulness): Does the answer contain ONLY information found in the context above? "
        "(Saying 'information not available in the record' is faithful.)\n"
        "Q2 (relevancy): Does the answer directly address the question?\n"
        "Q3 (citation): Does the answer avoid introducing medical facts NOT found in the context?\n\n"
        "Respond with exactly three lines, one per question:\n"
        "Q1: YES or NO\n"
        "Q2: YES or NO\n"
        "Q3: YES or NO"
    )

    def _parse_yn(line: str) -> float | None:
        word = re.split(r"[\s:]+", line.lower())[-1].rstrip(".")
        if word in {"yes", "có", "1", "true"}:
            return 1.0
        if word in {"no", "không", "0", "false"}:
            return 0.0
        return None

    total_rl_wait = 0.0
    error_count   = 0
    call_n        = 0

    while True:
        call_n += 1
        time.sleep(120)
        try:
            print(f"[gemini] requesting model={_JUDGE_MODEL}")
            resp = _get_client().models.generate_content(
                model=_JUDGE_MODEL,
                contents=prompt,
                config=_genai_types.GenerateContentConfig(temperature=0, max_output_tokens=32),
            )
            raw = resp.text.strip()
            print(f"    [judge] call={call_n} raw={raw!r}")

            # extract token usage if available
            um       = getattr(resp, "usage_metadata", None)
            j_in     = int(getattr(um, "prompt_token_count",     0) or 0)
            j_out    = int(getattr(um, "candidates_token_count", 0) or 0)

            lines  = [ln.strip() for ln in raw.splitlines() if ln.strip()]
            scores = [_parse_yn(lines[i]) if i < len(lines) else None for i in range(3)]

            if any(s is None for s in scores):
                print(f"    [judge] model_failure: unparseable output {raw!r}")
                return {
                    "status":            "model_failure",
                    "faithfulness":      0.0,
                    "answer_relevancy":  0.0,
                    "citation_accuracy": 0.0,
                    "wait_time":         total_rl_wait,
                    "judge_input_tokens":  j_in,
                    "judge_output_tokens": j_out,
                }

            return {
                "status":            "ok",
                "faithfulness":      scores[0],
                "answer_relevancy":  scores[1],
                "citation_accuracy": scores[2],
                "wait_time":         total_rl_wait,
                "judge_input_tokens":  j_in,
                "judge_output_tokens": j_out,
            }

        except Exception as exc:
            msg = str(exc)
            is_rate_limit = "429" in msg or "RESOURCE_EXHAUSTED" in msg

            if is_rate_limit:
                m    = re.search(r"retry in (\d+(?:\.\d+)?)s", msg)
                wait = float(m.group(1)) + 1 if m else 60
                total_rl_wait += wait
                if total_rl_wait > _MAX_RATE_LIMIT_WAIT:
                    print(f"    [judge] rate_limit_timeout after {total_rl_wait:.0f}s total wait")
                    return {
                        "status":            "rate_limit_timeout",
                        "faithfulness":      None,
                        "answer_relevancy":  None,
                        "citation_accuracy": None,
                        "wait_time":         total_rl_wait,
                        "judge_input_tokens":  0,
                        "judge_output_tokens": 0,
                    }
                print(f"    [judge] call={call_n} rate-limit — "
                      f"waiting {wait:.0f}s (total={total_rl_wait:.0f}s / {_MAX_RATE_LIMIT_WAIT}s)")
                time.sleep(wait)

            else:
                error_count += 1
                wait = 2 ** error_count
                print(f"    [judge] call={call_n} infra error {error_count}/{_ERROR_RETRIES}: {exc}")
                if error_count >= _ERROR_RETRIES:
                    print(f"    [judge] infra_failure after {error_count} errors")
                    return {
                        "status":            "infra_failure",
                        "faithfulness":      None,
                        "answer_relevancy":  None,
                        "citation_accuracy": None,
                        "wait_time":         total_rl_wait,
                        "judge_input_tokens":  0,
                        "judge_output_tokens": 0,
                    }
                time.sleep(wait)


# ── async query collection ────────────────────────────────────────────────────

async def _run_single(patient_id: str, question: str, thread_id: str) -> dict:
    import re
    from app.graphs.chat_graph import chat_graph
    config      = {"configurable": {"thread_id": thread_id}}
    state       = {"patient_id": patient_id, "question": question, "history": []}
    error_count = 0
    call_n      = 0
    while True:
        call_n += 1
        await asyncio.sleep(60)
        try:
            print(f"[gemini] requesting model={os.getenv('GEMINI_MODEL', 'gemini-3.1-flash-lite')}")
            t_infer = time.perf_counter()
            result  = await chat_graph.ainvoke(state, config=config)
            inference_s = time.perf_counter() - t_infer
            return {
                "answer":      result.get("answer", ""),
                "chunks":      result.get("chunks", []),
                "inference_s": round(inference_s, 3),
            }
        except Exception as exc:
            msg = str(exc)
            is_rate_limit = "429" in msg or "RESOURCE_EXHAUSTED" in msg
            if is_rate_limit:
                m    = re.search(r"retry in (\d+(?:\.\d+)?)s", msg)
                wait = float(m.group(1)) + 1 if m else 60
                print(f"    [collect] {patient_id} call={call_n} rate-limit — waiting {wait:.0f}s")
                await asyncio.sleep(wait)
            else:
                error_count += 1
                if error_count >= _COLLECT_RETRIES:
                    raise
                await asyncio.sleep(2 ** error_count)


async def _collect(patient_filter: list[str] | None, query_number: int | None = None) -> list[dict]:
    queries = SAMPLE_QUERIES
    if patient_filter:
        queries = [q for q in queries if q["patient_id"] in patient_filter]
    if query_number is not None:
        queries = [queries[query_number - 1]]

    ts    = str(int(time.time()))
    sem   = asyncio.Semaphore(_COLLECT_SEM)
    out   = [None] * len(queries)
    first_response_time: list[float] = []  # filled once by the first completed query

    async def _one(i: int, q: dict) -> None:
        async with sem:
            print(f"  [{i+1}/{len(queries)}] {q['patient_id']}: {q['question'][:65]}...")
            t_total = time.perf_counter()
            try:
                r           = await _run_single(q["patient_id"], q["question"],
                                                f"{q['patient_id']}_eval_{ts}_{i}")
                total_s     = time.perf_counter() - t_total
                answer      = r["answer"]
                chunks      = r["chunks"]
                inference_s = r.get("inference_s", 0.0)

                # token estimates (~4 chars per token — no tokenizer access)
                ctx_chars        = sum(len(c) for c in chunks)
                input_tok_est    = (len(q["question"]) + ctx_chars) // 4
                output_tok_est   = len(answer) // 4

                if not first_response_time:
                    first_response_time.append(total_s)

                out[i] = {
                    **q,
                    "answer":           answer,
                    "contexts":         chunks,
                    "error":            None,
                    "inference_s":      inference_s,
                    "total_latency_s":  round(total_s, 3),
                    "input_tokens_est": input_tok_est,
                    "output_tokens_est":output_tok_est,
                }
            except Exception as exc:
                print(f"    ERROR {q['patient_id']}: {exc}")
                out[i] = {
                    **q,
                    "answer":           "",
                    "contexts":         [],
                    "error":            str(exc),
                    "inference_s":      0.0,
                    "total_latency_s":  round(time.perf_counter() - t_total, 3),
                    "input_tokens_est": 0,
                    "output_tokens_est":0,
                }

    await asyncio.gather(*(_one(i, q) for i, q in enumerate(queries)))
    if first_response_time and _collector is not None:
        _collector.set_cold_start(first_response_time[0])
    return out  # type: ignore[return-value]


# ── acronym check ─────────────────────────────────────────────────────────────

def _acronym_report(responses: list[dict]) -> dict:
    details = []
    for r in responses:
        if r["error"] or not r["answer"]:
            continue
        violations = check_acronyms(r["answer"])
        details.append({
            "patient_id": r["patient_id"],
            "category":   r["category"],
            "question":   r["question"][:70],
            "violations": violations,
            "passed":     len(violations) == 0,
        })
    passed = sum(1 for d in details if d["passed"])
    return {
        "score":    round(passed / len(details), 3) if details else 0.0,
        "passed":   passed,
        "total":    len(details),
        "failures": [d for d in details if not d["passed"]],
    }


# ── LLM-as-judge scoring ──────────────────────────────────────────────────────

def _score_one(r: dict) -> dict:
    ctx = "\n\n".join(r["contexts"]) if r["contexts"] else "(no context retrieved)"
    print(f"    [ctx] {r['patient_id']} chunks={len(r['contexts'])} "
          f"chars={len(ctx)}  preview={ctx[:80]!r}")

    result = _score_all(ctx, r["question"], r["answer"])
    return {
        "patient_id":          r["patient_id"],
        "category":            r["category"],
        "question":            r["question"],
        "answer":              r["answer"][:300],
        "context_chunks":      len(r["contexts"]),
        "context_chars":       len(ctx),
        "context_preview":     ctx[:200],
        "judge_status":        result["status"],
        "faithfulness":        result["faithfulness"],
        "answer_relevancy":    result["answer_relevancy"],
        "citation_accuracy":   result["citation_accuracy"],
        "wait_time":           result["wait_time"],
        "judge_input_tokens":  result["judge_input_tokens"],
        "judge_output_tokens": result["judge_output_tokens"],
    }


def _llm_scores(responses: list[dict]) -> dict:
    valid     = [r for r in responses if not r["error"] and r["answer"]]
    per_query = [None] * len(valid)
    done      = 0

    with ThreadPoolExecutor(max_workers=_JUDGE_WORKERS) as pool:
        future_to_idx = {pool.submit(_score_one, r): i for i, r in enumerate(valid)}
        for fut in as_completed(future_to_idx):
            done += 1
            idx  = future_to_idx[fut]
            per_query[idx] = fut.result()
            q = per_query[idx]
            print(f"  [{done}/{len(valid)}] {q['patient_id']} / {q['category']} "
                  f"→ {q['judge_status']}")

    per_query = [q for q in per_query if q is not None]

    # push judge token counts into the collector
    if _collector is not None:
        for q in per_query:
            _collector.update_judge_tokens(
                q["patient_id"], q["question"][:65],
                q["judge_input_tokens"], q["judge_output_tokens"],
            )

    scoreable = [q for q in per_query if q["judge_status"] in {"ok", "model_failure"}]

    def _avg(key: str) -> float | None:
        vals = [q[key] for q in scoreable if q[key] is not None]
        return round(sum(vals) / len(vals), 3) if vals else None

    status_counts = {s: 0 for s in ("ok", "rate_limit_timeout", "infra_failure", "model_failure")}
    for q in per_query:
        status_counts[q["judge_status"]] = status_counts.get(q["judge_status"], 0) + 1

    return {
        "faithfulness":      _avg("faithfulness"),
        "answer_relevancy":  _avg("answer_relevancy"),
        "citation_accuracy": _avg("citation_accuracy"),
        "scored_n":          len(scoreable),
        "total_n":           len(per_query),
        "status_counts":     status_counts,
        "per_query":         per_query,
    }


# ── markdown report ───────────────────────────────────────────────────────────

def _na(v) -> str:
    if v is None:
        return "N/A"
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def _fmt_s(v) -> str:
    return f"{v:.2f} s" if v is not None else "N/A"


def _fmt_mb(v) -> str:
    if v is None:
        return "N/A"
    if v >= 1024:
        return f"{v/1024:.2f} GB ({v:.0f} MB)"
    return f"{v:.1f} MB"


